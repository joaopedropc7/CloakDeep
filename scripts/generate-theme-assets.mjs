#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const js = fs.readFileSync(path.join(root, "theme-code/assets/cross-store.js"), "utf8");
const css = fs.readFileSync(path.join(root, "theme-code/assets/cross-store.css"), "utf8");
const snippet = fs.readFileSync(path.join(root, "theme-code/snippets/cross-store-bridge.liquid"), "utf8");
const out = `// Generated by scripts/generate-theme-assets.mjs. Do not edit by hand.\n// Run: npm run theme:assets\n\nexport const THEME_JS = ${JSON.stringify(js)};\n\nexport const THEME_CSS = ${JSON.stringify(css)};\n\nexport const THEME_SNIPPET = ${JSON.stringify(snippet)};\n`;
fs.writeFileSync(path.join(root, "src/lib/theme/theme-assets.generated.ts"), out);
console.log("theme assets generated");
