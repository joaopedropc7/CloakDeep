#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env");
if (!fs.existsSync(envPath)) {
  console.warn("[runtime-env] .env não encontrado; gerando módulo vazio.");
}

const result = {};
if (fs.existsSync(envPath)) {
  const text = fs.readFileSync(envPath, "utf8");
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    let value = rawValue.trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
}

const out = `// Generated by scripts/generate-runtime-env.mjs. Do not edit by hand.\n// Source: .env (versioned). Run: npm run env:generate\n\nexport const RUNTIME_ENV: Record<string, string> = ${JSON.stringify(
  result,
  null,
  2,
)};\n`;
fs.writeFileSync(path.join(root, "src/lib/env.generated.ts"), out);
console.log(`[runtime-env] generated ${Object.keys(result).length} variables`);
